class DDTableTests(unittest.TestCase):
    def test_all_twenty_explicit_entries_and_json_cache_roundtrip(self) -> None:
        table = VERIFICATION_TABLE
        encoded = json.loads(json.dumps(table.to_dict()))
        self.assertEqual(set(encoded), {"N", "E", "S", "W"})
        for seat in DECLARERS:
            self.assertEqual(set(encoded[seat.value]), {"C", "D", "H", "S", "NT"})
            for strain in STRAINS:
                self.assertEqual(table.tricks(seat, strain), encoded[seat.value][strain.value])
        self.assertEqual(DDTable.from_dict(encoded), table)
        self.assertEqual(hash(DDTable.from_dict(encoded)), hash(table))

    def test_table_and_axes_are_immutable(self) -> None:
        with self.assertRaises(FrozenInstanceError):
            VERIFICATION_TABLE.values = ()
        data = VERIFICATION_TABLE.to_dict()
        data["N"]["C"] = 13
        self.assertEqual(VERIFICATION_TABLE.tricks(Seat.NORTH, Strain.CLUBS), 2)
        with self.assertRaises(TypeError):
            VERIFICATION_TABLE.tricks("N", Strain.CLUBS)

    def test_reject_incomplete_mutable_or_noninteger_entries(self) -> None:
        for values in ((), [[0] * 5] * 4, ((0,) * 4,) * 4,
                       ((14,) * 5,) * 4, ((-1,) * 5,) * 4,
                       ((True,) * 5,) * 4, ((3.0,) * 5,) * 4):
            with self.subTest(values=values), self.assertRaises(ValueError):
                DDTable(values)
        for data in ({}, {"N": {}}, {seat.value: {"C": 1} for seat in DECLARERS}):
            with self.subTest(data=data), self.assertRaises(ValueError):
                DDTable.from_dict(data)


class PBNTests(unittest.TestCase):
    def test_known_east_first_input_maps_to_absolute_seats_and_suits(self) -> None:
        deal = deal_from_pbn(PUBLISHED_FIXTURES[1][0])
        self.assertEqual(deal_to_pbn(deal),
                         "N:AK96.KQ8.A98.K63 QJT5432.T.6.QJ82 .J97543.K7532.94 87.A62.QJT4.AT75")
        self.assertIn(Card("A", "S"), deal.north.cards)
        self.assertIn(Card("Q", "C"), deal.east.cards)
        self.assertFalse(any(card.suit == "S" for card in deal.south.cards))

    def test_all_start_seats_roundtrip_without_rotating_actual_deal(self) -> None:
        for pbn, _ in PUBLISHED_FIXTURES:
            deal = deal_from_pbn(pbn)
            for first in DECLARERS:
                with self.subTest(pbn=pbn, first=first):
                    actual = deal_from_pbn(deal_to_pbn(deal, first))
                    for seat in DECLARERS:
                        self.assertEqual(set(actual.hand(seat).cards), set(deal.hand(seat).cards))

    def test_reject_invalid_or_partial_pbn(self) -> None:
        invalid = ("", "X:...", "N:...", "N:A.A.A.A A.A.A.A A.A.A.A A.A.A.A",
                   "N:AKQJT98765432... AKQJT98765432... AKQJT98765432... AKQJT98765432...",
                   PUBLISHED_FIXTURES[0][0].replace("QJ6", "QJx"))
        for pbn in invalid:
            with self.subTest(pbn=pbn), self.assertRaises(ValueError):
                deal_from_pbn(pbn)
        with self.assertRaises(TypeError):
            deal_to_pbn(None)

    def test_void_dash_is_normalized_to_empty_suit(self) -> None:
        pbn = PUBLISHED_FIXTURES[1][0]
        self.assertEqual(deal_to_pbn(deal_from_pbn(pbn.replace(" .J", " -.J"))),
                         deal_to_pbn(deal_from_pbn(pbn)))

    def test_mutated_core_card_lists_are_rejected_before_native_call(self) -> None:
        original = deal_from_pbn(PUBLISHED_FIXTURES[0][0])
        cards = list(original.north.cards)
        deal = Deal(
            Hand(cards), Hand(list(original.east.cards)),
            Hand(list(original.south.cards)), Hand(list(original.west.cards)),
        )
        cards[0] = cards[1]
        with self.assertRaisesRegex(ValueError, "duplicate"):
            deal_to_pbn(deal)


class DDSFailureTests(unittest.TestCase):
    def test_missing_library_is_explicit_even_if_a_python_module_exists(self) -> None:
        with self.assertRaisesRegex(DDSUnavailableError, "tools/dds/build.py"):
            DDSAdapter(Path(".runtime/dds/does-not-exist.so"))

    def test_manifest_rejects_wrong_pin_hash_or_missing_provenance(self) -> None:
        metadata = {
            "schema_version": 1, "version": dds.DDS_VERSION,
            "source_url": dds.SOURCE_URL, "source_commit": dds.SOURCE_COMMIT,
            "license": "Apache-2.0", "threading": "single", "constructor": False,
            "excluded_source_units": ["dds.cpp"], "compile_flags": list(dds.BUILD_FLAGS),
            "patch_id": dds.PATCH_ID, "patch_sha256": dds.PATCH_SHA256,
            "patched_system_sha256": dds.PATCHED_SYSTEM_SHA256, "compiler": "test compiler",
            "library_sha256": hashlib.sha256(b"test binary").hexdigest(),
        }
        metadata["build_id"] = hashlib.sha256(
            json.dumps(metadata, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()
        with (
            patch.object(Path, "is_file", return_value=True),
            patch.object(Path, "read_text", return_value=json.dumps(metadata)),
            patch.object(Path, "read_bytes", return_value=b"test binary"),
        ):
            self.assertEqual(dds._build_metadata(Path("libdds.so")), metadata)
        for key, bad in (("source_commit", "untrusted"), ("version", "3.0.0"),
                         ("library_sha256", "wrong"), ("build_id", "wrong")):
            damaged = {**metadata, key: bad}
            with (
                self.subTest(key=key),
                patch.object(Path, "is_file", return_value=True),
                patch.object(Path, "read_text", return_value=json.dumps(damaged)),
                patch.object(Path, "read_bytes", return_value=b"test binary"),
                self.assertRaises(DDSConfigurationError),
            ):
                dds._build_metadata(Path("libdds.so"))
        with (
            patch.object(Path, "is_file", return_value=True),
            patch.object(Path, "read_text", side_effect=FileNotFoundError()),
            self.assertRaisesRegex(DDSConfigurationError, "manifest"),
        ):
            dds._build_metadata(Path("libdds.so"))
        with (
            patch.object(Path, "is_file", return_value=True),
            patch.object(Path, "read_text", return_value=json.dumps(metadata)),
            patch.object(Path, "read_bytes", side_effect=PermissionError()),
            self.assertRaisesRegex(DDSConfigurationError, "Cannot read"),
        ):
            dds._build_metadata(Path("libdds.so"))

    def test_library_errors_include_code_and_deal_not_a_table(self) -> None:
        def error_message(code, message):
            message.value = b"PBN string error"

        adapter = DDSAdapter.__new__(DDSAdapter)
        adapter._library = SimpleNamespace(
            CalcDDtablePBN=lambda *_: -99, ErrorMessage=error_message,
        )
        deal = deal_from_pbn(PUBLISHED_FIXTURES[0][0])
        with self.assertRaises(DDSSolveError) as raised:
            adapter.solve(deal)
        self.assertEqual(raised.exception.code, -99)
        self.assertEqual(raised.exception.pbn, deal_to_pbn(deal))
        self.assertIn("PBN string error", str(raised.exception))

    def test_incomplete_success_is_an_error_not_zero_tricks(self) -> None:
        adapter = DDSAdapter.__new__(DDSAdapter)
        adapter._library = SimpleNamespace(CalcDDtablePBN=lambda *_: 1)
        with self.assertRaisesRegex(DDSSolveError, "incomplete 20-entry"):
            adapter.solve(deal_from_pbn(PUBLISHED_FIXTURES[0][0]))

    def test_simultaneous_calls_on_different_adapters_are_serialized(self) -> None:
        active = maximum = 0
        guard = threading.Lock()

        def solve(_pbn, output):
            nonlocal active, maximum
            with guard:
                active += 1
                maximum = max(maximum, active)
            time.sleep(0.005)
            for row in output._obj.resTable:
                for index in range(4):
                    row[index] = 7
            with guard:
                active -= 1
            return 1

        adapters = [DDSAdapter.__new__(DDSAdapter) for _ in range(2)]
        for adapter in adapters:
            adapter._library = SimpleNamespace(CalcDDtablePBN=solve)
        deal = deal_from_pbn(PUBLISHED_FIXTURES[0][0])
        with ThreadPoolExecutor(max_workers=4) as executor:
            results = list(executor.map(lambda index: adapters[index % 2].solve(deal), range(8)))
        self.assertEqual(maximum, 1)
        self.assertEqual(results, [DDTable(((7,) * 5,) * 4)] * 8)

    def test_self_test_mismatch_is_not_available(self) -> None:
        adapter = SimpleNamespace(solve=lambda _: DDTable(((0,) * 5,) * 4))
        with self.assertRaisesRegex(DDSConfigurationError, "published-fixture self-test"):
            verify_adapter(adapter)


class RealDDSIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        try:
            cls.adapter = DDSAdapter()
        except DDSUnavailableError as exc:
            if os.environ.get("BRIDGE_DDS_REQUIRED") == "1":
                raise AssertionError(f"required real DDS integration unavailable: {exc}") from exc
            raise unittest.SkipTest(f"real DDS unavailable, not verified: {exc}") from exc

    def test_five_independent_published_full_tables(self) -> None:
        for pbn, expected in PUBLISHED_FIXTURES:
            with self.subTest(pbn=pbn):
                table = self.adapter.solve(deal_from_pbn(pbn))
                self.assertEqual(table, DDTable(expected))
                for seat_index, seat in enumerate(DECLARERS):
                    for strain_index, strain in enumerate(STRAINS):
                        self.assertEqual(table.tricks(seat, strain),
                                         expected[seat_index][strain_index])

    def test_real_repeated_solve_and_external_json_cache_are_identical(self) -> None:
        deal = deal_from_pbn(VERIFICATION_PBN)
        first = self.adapter.solve(deal)
        cached = DDTable.from_dict(json.loads(json.dumps(first.to_dict())))
        self.adapter.solve(deal_from_pbn(PUBLISHED_FIXTURES[0][0]))
        self.assertEqual(self.adapter.solve(deal), first)
        self.assertEqual(self.adapter.solve(deal), cached)
        self.assertEqual(DDSAdapter().solve(deal), first)

    def test_physical_seat_rotations_preserve_declarer_not_opening_leader(self) -> None:
        deal = deal_from_pbn(VERIFICATION_PBN)
        for offset in (1, 2, 3):
            rotated = Deal(*(deal.hand(DECLARERS[(index + offset) % 4]) for index in range(4)))
            actual = self.adapter.solve(rotated)
            for index, seat in enumerate(DECLARERS):
                for strain in STRAINS:
                    self.assertEqual(
                        actual.tricks(seat, strain),
                        VERIFICATION_TABLE.tricks(DECLARERS[(index + offset) % 4], strain),
                    )

    def test_suit_permutation_maps_strain_axes_not_nt(self) -> None:
        deal = deal_from_pbn(VERIFICATION_PBN)
        suits = {"S": "C", "C": "H", "H": "D", "D": "S"}
        permuted = Deal(*(
            Hand(tuple(Card(card.rank, suits[card.suit]) for card in deal.hand(seat).cards))
            for seat in DECLARERS
        ))
        actual = self.adapter.solve(permuted)
        for seat in DECLARERS:
            for strain in STRAINS:
                target = strain if strain == Strain.NOTRUMP else Strain(suits[strain.value])
                self.assertEqual(actual.tricks(seat, target), VERIFICATION_TABLE.tricks(seat, strain))

    def test_real_concurrent_calls_are_repeatable(self) -> None:
        with ThreadPoolExecutor(max_workers=3) as executor:
            tables = list(executor.map(
                lambda _: DDSAdapter().solve(deal_from_pbn(VERIFICATION_PBN)), range(4),
            ))
        self.assertEqual(tables, [VERIFICATION_TABLE] * 4)

    def test_provenance_is_pinned_immutable_and_json_safe(self) -> None:
        provenance = self.adapter.provenance
        self.assertEqual(provenance.version, "2.9.0")
        self.assertEqual(provenance.source_commit, "8d75755c8df81999557758c9757514edb94017bc")
        self.assertEqual(provenance.oracle_kind, "dds")
        self.assertEqual(provenance.license, "Apache-2.0")
        self.assertEqual(provenance.threads, 1)
        self.assertEqual(len(provenance.library_sha256), 64)
        self.assertEqual(len(provenance.build_id), 64)
        self.assertEqual(json.loads(json.dumps(provenance.to_dict())), provenance.to_dict())
        with self.assertRaises(FrozenInstanceError):
            provenance.version = "mock"
        verify_adapter(self.adapter)


